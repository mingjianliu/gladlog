/** The shaman's Tremor Totem cast. */
export const TREMOR_TOTEM_CAST_SPELL_ID = "8143";
/** A fear ending this soon after a friendly Tremor Totem lands was ended BY it.
 * Measured (GH #100, 300 files, 50 fears with a totem dropped mid-fear): removal
 * lag after the summon p50 0 s, p90 0.02 s, 49/50 within 1.5 s. */
export const TREMOR_BREAK_MAX_LAG_MS = 500;

/**
 * The friendly Tremor Totem cast that ended this CC, or null.
 *
 * The totem sources NO log event of its own, so this is the only tremor fact
 * the log supports deterministically: the totem was dropped WHILE the fear was
 * running and the fear ended the same instant. A totem that was already up
 * when the fear landed is deliberately not credited — fear also breaks on
 * damage (44.8 % of fears end within 1.5 s with no totem at all), so a short
 * fear under a standing totem is suggestive, never attributable.
 */
export function tremorTotemBreak(
  cc: Pick<ICCInstance, "spellId" | "atSeconds" | "durationSeconds">,
  matchStartMs: number,
  teammates: Pick<ICombatUnit, "name" | "class" | "spellCastEvents">[],
): { shamanName: string; castMs: number } | null {
  if (!TREMOR_BREAKABLE_CC_IDS.has(cc.spellId)) return null;
  const appliedMs = matchStartMs + cc.atSeconds * 1000;
  const endedMs = appliedMs + cc.durationSeconds * 1000;
  for (const mate of teammates) {
    if (mate.class !== CombatUnitClass.Shaman) continue;
    for (const e of mate.spellCastEvents) {
      if (
        e.spellId !== TREMOR_TOTEM_CAST_SPELL_ID ||
        e.logLine.event !== LogEvent.SPELL_CAST_SUCCESS
      )
        continue;
      const castMs = e.logLine.timestamp;
      if (
        castMs > appliedMs &&
        endedMs >= castMs &&
        endedMs - castMs <= TREMOR_BREAK_MAX_LAG_MS
      )
        return { shamanName: mate.name, castMs };
    }
  }
  return null;
}

/**
 * How far a press that ended a CC sits from that CC's REMOVED line. Measured
 * on the 605-file capture slice (2026-10-01, `fix-T1015/immbreak.py`): of the
 * caster's CC endings within ±500 ms of an own Divine Shield cast (417
 * casts), 259 are 0–3 ms before the cast line, 9 are 3–10 ms before, 7 are
 * 10–50 ms before, 30 earlier still — and none after it; Ice Block 74 / 1 / 2
 * / 5 (343 casts). The 0–10 ms group ends CCs far short of their length (a
 * 0.66 s Psychic Scream, a 1.2 s Hammer of Justice); the 10–50 ms group
 * already holds CCs that simply ran out (a 3.0 s Dragon's Breath, 29 ms
 * before the press). So 10, not the trinket binder's 50 / 250: a press right
 * after a CC expired on its own must not read as having broken it.
 */
export const PRESS_ENDED_CC_LAG_MS = 10;

/**
 * Did this cast END the CC window — is its line the one sitting at the
 * window's removal? (Triage 2026-09-29, enemy-def F-E20.) A press that purges
 * a CC is logged right AFTER the CC's own REMOVED, so it is never "inside"
 * the CC and no strict-inside test can see it. True when the cast is at or
 * after the CC landed and within `PRESS_ENDED_CC_LAG_MS` of its removal; a
 * press in the middle of a CC that then runs on ended nothing, and neither
 * did a press made before the CC landed.
 */
export function castEndedCcWindow(
  window: ICCBreakableWindow,
  castMs: number,
): boolean {
  return (
    castMs >= window.applyMs &&
    Math.abs(castMs - window.removeMs) <= PRESS_ENDED_CC_LAG_MS
  );
}

/**
 * The CC'd player's own immunity press that ended this CC, or null (F-E20):
 * e10c6bea's Hammer of Justice is REMOVED at 165.286 inside Divine Shield's
 * debuff purge (SPELL_CAST_SUCCESS 165.287), and the `[CC ON TEAM]` line read
 * as a 3 s stun that ran out. `IMMUNITY_IDS` is the `[ENEMY DEF]` immune set.
 */
export function immunityBreak(
  cc: Pick<ICCInstance, "atSeconds" | "durationSeconds">,
  matchStartMs: number,
  player: Pick<ICombatUnit, "id" | "spellCastEvents">,
): { spellId: string; spellName: string; castMs: number } | null {
  const window = {
    applyMs: matchStartMs + Math.round(cc.atSeconds * 1000),
    removeMs:
      matchStartMs + Math.round((cc.atSeconds + cc.durationSeconds) * 1000),
  };
  for (const e of player.spellCastEvents) {
    if (e.logLine.event !== LogEvent.SPELL_CAST_SUCCESS) continue;
    if (!e.spellId || !IMMUNITY_IDS.has(e.spellId)) continue;
    // on the player themselves: a Blessing of Protection thrown on a teammate
    // the instant the paladin's own stun ran out ended nothing of his
    if (
      e.destUnitId &&
      e.destUnitId !== "0000000000000000" &&
      e.destUnitId !== player.id
    )
      continue;
    const castMs = e.logLine.timestamp;
    if (!castEndedCcWindow(window, castMs)) continue;
    return {
      spellId: e.spellId,
      spellName: getEnglishSpellName(e.spellId, e.spellName),
      castMs,
    };
  }
  return null;
}

/**
 * DEFENSIVE-001 (cc-avoidable, 2026-08-07, BACKLOG #18 second batch): pure
 * derivation of "which avoidance spell ids would explain dodging this CC
 * application" — the identical gating rules the CC Avoidance Correlation
 * sweep below applies inline while deciding `ccAvoidedInstances` (buff
 * school gate: a magic-only immunity cannot explain a physical CC; Druid
 * forms only credited for Polymorph/Hex, never a ground CC or another
 * targeted CC; mobility credited for any ground CC, or a targeted CC only
 * via TARGETED_CC_DODGE_SPELLS). Extracted as its own exported pure function
 * — rather than re-derived a second time in candidateFindings.ts — because
 * cc-avoidable asks a different question of the SAME predicate: not "was
 * this CC avoided" (ccAvoidedInstances, computed from what actually
 * happened), but "for a CC that landed, which of these tools WOULD have
 * applied" (a hypothetical the inline sweep never needs to ask, because it
 * only runs for CCs that were NOT credited with an avoidance). Shared-
 * predicate rule (CLAUDE.md): the gating logic for "which avoidance ids
 * apply to this CC" lives in exactly one place; both call sites (this
 * function and the inline sweep) must be read together when either changes.
 * Additive: this function is never called from the inline sweep above, so it
 * changes zero existing behavior.
 */
export function applicableCCAvoidanceIds(
  ccSpellId: string,
  ccSpellName: string,
): Set<string> {
  const out = new Set<string>();
  const isGroundCC = GROUND_CC_SPELL_IDS.has(ccSpellId);
  const isPolyOrHex = /polymorph|hex/i.test(ccSpellName);

  // A. Buff-based avoidance. 官方优先(GH #29 阶段 1):学派掩码知道两边时直接
  // 判定「这个免疫挡不挡得住这个控」;官方缺数据时才回退到原来的手工单向规则。
  //
  // 原规则只有一个方向 —— 「纯魔法免疫挡不住物理控」—— 没有反向,于是**纯物理
  // 免疫被推荐去躲魔法控**:250 场实测 2 条建议用保护祝福(SCHOOL_IMMUNITY 掩码
  // = 1,仅物理)躲 Sleep Walk(SchoolMask = 8,自然系)。
  //
  // 回退分支里 CC 的「是不是物理」也改问官方(`isPhysicalSpell`),手工的
  // PHYSICAL_CC_IDS 只在官方没有该 id 时兜底:那 9 条本身没写错,但漏了制裁之锤
  // (神圣)、暗影之怒(暗影)、混沌新星(多学派)这些魔法控 —— 手工名单证不了全。
  for (const buffId of CC_AVOIDANCE_BUFF_SPELLS.keys()) {
    const covers = immunityCoversSpell(buffId, ccSpellId);
    if (covers === false) continue; // 官方判定:挡不住
    if (covers === undefined) {
      // 官方缺这个免疫的 aura39 行(反魔法护罩/法术反射/剑刃风暴/龟盾…)
      const ccIsPhysical =
        isPhysicalSpell(ccSpellId) ?? PHYSICAL_CC_IDS.has(ccSpellId);
      if (MAGIC_ONLY_IMMUNITY_IDS.has(buffId) && ccIsPhysical) continue;
    }
    out.add(buffId);
  }
  if (isPolyOrHex) {
    for (const formId of DRUID_FORM_BUFFS.keys()) out.add(formId);
  }
  // B. Mobility-based avoidance: any repositioning spell dodges a ground CC;
  // only the TARGETED_CC_DODGE_SPELLS subset dodges a targeted CC. Druid
  // forms never count here (H14: shapeshifting does not reposition the
  // player out of a ground AoE, and the buff branch above already handles
  // their Polymorph/Hex-only case).
  for (const moveId of REPOSITIONING_SPELL_IDS.keys()) {
    if (DRUID_FORM_BUFFS.has(moveId)) continue;
    if (isGroundCC || TARGETED_CC_DODGE_SPELLS.has(moveId)) out.add(moveId);
  }
  return out;
}

