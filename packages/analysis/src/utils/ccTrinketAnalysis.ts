export function detectTrinketType(unit: ICombatUnit): TrinketType {
  const trinketSlots = (unit.info?.equipment ?? []).filter((_, i) =>
    [12, 13].includes(i),
  );
  if (trinketSlots.some((e) => RELENTLESS_ITEM_IDS.has(e.id)))
    return "Relentless";
  if (trinketSlots.some((e) => ADAPTATION_ITEM_IDS.has(e.id)))
    return "Adaptation";
  if (
    trinketSlots.some((e) => GLADIATOR_ITEM_IDS.has(e.id)) ||
    (unit.spellCastEvents ?? []).some(
      (e) => e.spellId === MEDALLION_SPELL_ID,
    )
  )
    return "Gladiator";
  if (trinketSlots.length > 0) return "None";
  return "Unknown";
}

