export function formatCCTrinketForContext(
  summaries: IPlayerCCTrinketSummary[],
): string[] {
  const lines: string[] = [];
  lines.push("CC RECEIVED BY YOUR TEAM (enemies CCing you) + TRINKET USAGE:");

  const hasCCData = summaries.some((s) => s.ccInstances.length > 0);
  if (!hasCCData) {
    lines.push("  No hard CC events detected on your team.");
    return lines;
  }

  for (const s of summaries) {
    if (s.ccInstances.length === 0) continue;

    // Aggregate CC counts by type
    const countBySpell = new Map<string, number>();
    let immuneOrReducedCount = 0;
    let meleeCCCount = 0;
    const missedTrinketCount = s.missedTrinketWindows.length;

    for (const cc of s.ccInstances) {
      countBySpell.set(cc.spellName, (countBySpell.get(cc.spellName) ?? 0) + 1);
      if (cc.drInfo && cc.drInfo.level !== "Full") immuneOrReducedCount++;
      if (
        cc.distanceYards !== null &&
        cc.distanceYards <= 8 &&
        cc.losBlocked !== true
      )
        meleeCCCount++;
    }

    const ccBreakdown = [...countBySpell.entries()]
      .sort((a, b) => b[1] - a[1])
      .map(([name, count]) => `${count}× ${name}`)
      .join(", ");
    const trinketCdStr =
      s.trinketType === "Relentless" ||
      s.trinketType === "Unknown" ||
      s.trinketType === "None"
        ? s.trinketType === "None"
          ? "no PvP trinket"
          : s.trinketType
        : `${s.trinketType} trinket`;

    const notes: string[] = [];
    if (immuneOrReducedCount > 0)
      notes.push(`${immuneOrReducedCount} reduced/immune DR`);
    if (meleeCCCount > 0) notes.push(`${meleeCCCount} at melee range`);
    if (missedTrinketCount > 0) {
      const totalDmg = s.missedTrinketWindows.reduce(
        (sum, w) => sum + w.damageTakenDuring,
        0,
      );
      notes.push(
        `⚠ ${missedTrinketCount} missed trinket window(s) (${Math.round(totalDmg / 1000)}k dmg total)`,
      );
    }
    const noteStr = notes.length > 0 ? ` [${notes.join("; ")}]` : "";

    // Trinket use times outside CC windows
    const trinketResponseWindowS = TRINKET_RESPONSE_WINDOW_MS / 1000;
    const offCCUses = s.trinketUseTimes.filter(
      (t) =>
        !s.ccInstances.some(
          (cc) => Math.abs(cc.atSeconds - t) <= trinketResponseWindowS,
        ),
    );
    const trinketStr =
      offCCUses.length > 0
        ? `${trinketCdStr} used off-CC at ${offCCUses.map(fmtTime).join(", ")}`
        : trinketCdStr;

    lines.push(
      `  ${s.playerSpec} (${s.playerName}): ${s.ccInstances.length} CC — ${ccBreakdown} | ${trinketStr}${noteStr}`,
    );

    // Per-window detail for missed trinket windows — the highest-value CC instances.
    // Position annotation (distance / LoS at application) only when advanced logging supplied it.
    for (const w of s.missedTrinketWindows) {
      const posStr =
        w.distanceYards !== null
          ? ` — ${w.distanceYards}yd from caster${w.losBlocked === true ? ", LoS blocked" : ""}`
          : "";
      lines.push(
        `    ⚠ Missed trinket: ${fmtTime(w.atSeconds)} ${w.spellName} (${Math.round(w.durationSeconds)}s, ${Math.round(w.damageTakenDuring / 1000)}k dmg)${posStr}`,
      );
    }
  }

  return lines;
}
