/** BACKLOG #36(b): what the player did in the `POST_KICK_WINDOW_S` after
 * eating a kick. The lockout duration itself carries no information (840
 * corpus kicks all land in 3–4s — modern school lockouts are fixed), so the
 * teachable severity axis is the BEHAVIOR while locked:
 *   - "switched": cast something the lock does not cover — a spell with at
 *     least one school outside the interrupted spell's (`schoolLockedBy`;
 *     until 2026-10-01 the test was "shares no bit", which called Starsurge
 *     locked by a Nature lock while the log shows it going out)
 *   - "acted": cast something, but a fully locked or unknown school (waited
 *     the lockout out, or masks unavailable — three-state data, never guessed)
 *   - "idle": zero casts for the whole window — the paralysis case
 *
 * ⚠ **"switched" is NOT "kept playing through the lockout"** — that reading
 * was in this comment until 2026-09-06 and it is wrong. The test is a school
 * mask, not a hardcast, so ANY cast qualifies: measured over 400 corpus
 * rounds, only 16/292 switches had their own `SPELL_CAST_START`; the rest
 * were instants — Cat Form, Hover, Will to Survive, even the PvP trinket
 * (`packages/eval/scripts/postKickSwitchAudit.ts`). Downstream text must
 * therefore name the cast and qualify it (`switchSpellName` /
 * `switchWasHardCast`) rather than assert the player kept casting.
 *
 * The same correction applies to the corpus anchor below: what it measured
 * is the rate of pressing ANY off-school ability, not of casting through a
 * lockout, so **it does not support a severity ordering on its own**. Left
 * here because the rate itself is real and reproducible.
 *
 * Corpus anchor (500 matches, healer-study school_probe): switch rates track
 * spec kit ceilings (Disc 76–80% vs Holy Paladin 8%), so cross-spec
 * comparison is kit × skill; within-spec, the idle rate is the coachable
 * half. */
export type PostKickBehavior = "switched" | "acted" | "idle";

/**
 * How coachable a post-kick behaviour is — **lower sorts first** (most
 * coachable), consumed by `kickEatenEvents`' cap selection.
 *
 * Replaces the flat `idle 0 / acted 1 / switched 2` table (2026-09-06). That
 * table asserted "switched is the least coachable", and the assertion is
 * only supported for the switches that were a real hardcast: measured over
 * 400 rounds, that is **16 of 292**. For the other 95% — an off-school
 * instant — the old rank had no evidence behind it at all, and the concrete
 * cost was that a player who was shut down and pressed one instant heal
 * (Holy Priest 1bad0a5c t=15.4, the whole 5 s window is that single cast)
 * sorted BELOW someone who cast normally after the lockout expired.
 *
 * The three tiers are exactly what the data supports, no more:
 *  - `0` **idle** — zero casts for the whole window. The paralysis case.
 *  - `1` **acted, or switched-by-instant** — did something, but nothing here
 *    says whether it helped. An off-school instant can be a good disengage
 *    (Cat Form + Wild Charge) or near-paralysis (one instant heal), and this
 *    module **cannot tell those apart** — so they are not ranked against
 *    each other or against `acted`. Deliberately a tie.
 *  - `2` **switched by a real hardcast** — demonstrably kept casting through
 *    the lockout. The only group the "least coachable" claim was ever true
 *    of.
 *
 * `switchWasHardCast === null` (no cast-start data, old archive) stays in
 * tier 1: absence of evidence must not promote a line into the
 * "demonstrably fine" tier.
 *
 * `rejectedPresses` (2026-09-24, reliability audit A1): the number of the
 * player's presses in the same window that the game REJECTED
 * (SPELL_CAST_FAILED, after the shared `filterIntentGuardEvidence`). `idle`
 * only means "no SUCCESSFUL cast": 7c598eeb r0 @91 was idle with 7 rejected
 * presses (Mind Control out of line of sight, then while disoriented) and sat
 * in tier 0 as the paralysis case. A player who kept pressing is not
 * paralysed, so an idle line with rejected presses drops to tier 1 — it
 * cannot claim "did something useful" either, which is exactly tier 1.
 */
export function postKickSeverityRank(
  inst: Pick<IInterruptInstance, "postKick" | "switchWasHardCast">,
  rejectedPresses = 0,
): number {
  if (inst.postKick === "idle") return rejectedPresses > 0 ? 1 : 0;
  if (inst.postKick === "switched" && inst.switchWasHardCast === true) return 2;
  return 1;
}

